const phraseMaps = Object.fromEntries(
  ["ka", "en", "ru"].map((lang, index) => [
    lang,
    new Map(phrases.flatMap((entry) => entry.map((source) => [normalize(source), entry[index + 1]]))),
  ]),
);

const LanguageContext = createContext({
  language: DEFAULT_LANG,
  setLanguage: () => {},
});

function normalize(value) {
  return String(value).replace(/\s+/g, " ").trim();
}

function translateValue(value, language) {
  const key = normalize(value);
  return phraseMaps[language]?.get(key) ?? value;
}

function hasOnlyInlineContent(element) {
  return [...element.children].every((child) =>
    ["BR", "SPAN", "STRONG", "EM", "B", "I"].includes(child.tagName),
  );
}

function shouldSkip(node) {
  const parent = node.nodeType === Node.TEXT_NODE ? node.parentElement : node;
  return (
    !parent ||
    parent.closest("[data-i18n-skip], [translate='no'], input, script, style")
  );
}

function translateDom(language) {
  document.documentElement.lang = language;

  document
    .querySelectorAll("p, h1, h2, h3, h4, button, a, div, label")
    .forEach((element) => {
      if (
        element.closest("[data-i18n-skip], [translate='no'], input, textarea, select, script, style") ||
        !hasOnlyInlineContent(element)
      ) {
        return;
      }

      const current = element.textContent;
      const translated = translateValue(current, language);

      if (translated !== current) {
        element.textContent = translated;
      }
    });

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];

  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  textNodes.forEach((node) => {
    if (shouldSkip(node) || !normalize(node.nodeValue)) {
      return;
    }
    const translated = translateValue(node.nodeValue, language);
    if (translated !== node.nodeValue) {
      node.nodeValue = translated;
    }
  });

  document.querySelectorAll("[placeholder], [aria-label], [alt], [title]").forEach((element) => {
    if (element.closest("[data-i18n-skip], [translate='no']")) {
      return;
    }
    ["placeholder", "aria-label", "alt", "title"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) {
        return;
      }
      const current = element.getAttribute(attribute);
      const translated = translateValue(current, language);
      if (translated !== current) {
        element.setAttribute(attribute, translated);
      }
    });
  });

  document.querySelectorAll("textarea").forEach((element) => {
    if (element.closest("[data-i18n-skip], [translate='no']")) {
      return;
    }

    const translated = translateValue(element.value, language);
    if (translated !== element.value) {
      element.value = translated;
    }
  });
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(DEFAULT_LANG);
  const value = useMemo(() => ({ language, setLanguage }), [language]);

  useEffect(() => {
    localStorage.setItem(LANG_STORAGE_KEY, language);
    const run = () => translateDom(language);
    const timeout = window.setTimeout(run, 0);
    const observer = new MutationObserver(run);
    observer.observe(document.body, { childList: true, subtree: true });

    return () => {
      window.clearTimeout(timeout);
      observer.disconnect();
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export function LanguageSwitcher() {
  const { language, setLanguage } = useContext(LanguageContext);
  const options = [
    { id: "ka", label: "ქარ" },
    { id: "en", label: "EN" },
    { id: "ru", label: "RU" },
  ];

  return (
    <div
      data-i18n-skip
      style={{
        position: "fixed",
        right: "14px",
        top: "14px",
        zIndex: 2000,
        display: "flex",
        gap: "6px",
        padding: "6px",
        borderRadius: "999px",
        background: "rgba(8,8,14,0.86)",
        border: "1px solid rgba(255,255,255,0.16)",
        backdropFilter: "blur(10px)",
      }}
    >
      {options.map((option) => {
        const active = language === option.id;
        return (
          <button
            key={option.id}
            type="button"
            onClick={() => setLanguage(option.id)}
            style={{
              minWidth: "42px",
              border: "none",
              borderRadius: "999px",
              padding: "8px 10px",
              color: "#ffffff",
              background: active ? "linear-gradient(90deg, #ff2d7a, #2452ff)" : "transparent",
              fontWeight: 800,
              cursor: "pointer",
            }}
          >
            {option.label}
          </button>
        );
      })}
    </div>
  );
}
